def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("output")
    args = parser.parse_args()

    source = polib.pofile(args.source)
    official_count, custom_count, mechanical_count = translate(source)
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    catalogs = {module: make_catalog(source.metadata) for module in MODULES}
    unmapped = []
    for entry in source:
        if not entry.msgid:
            continue
        modules = entry_modules(entry)
        if not entry.msgstr:
            unmapped.append(entry.msgid)
        for module in modules:
            catalogs[module].append(entry)

    javascript_occurrence = (
        "code:addons/construction_ui/static/src/workspace_hub/workspace_hub.js",
        "0",
    )
    for entry in catalogs["construction_ui"]:
        if entry.msgid in CUSTOM:
            comments = (entry.comment or "").splitlines()
            if "odoo-javascript" not in comments:
                comments.append("odoo-javascript")
                entry.comment = "\n".join(filter(None, comments))
            if javascript_occurrence not in entry.occurrences:
                entry.occurrences.append(javascript_occurrence)

    existing_ui = {entry.msgid for entry in catalogs["construction_ui"]}
    for msgid, msgstr in CUSTOM.items():
        if msgid not in existing_ui and msgid not in ("Task Label", "Project Overview"):
            catalogs["construction_ui"].append(
                polib.POEntry(
                    msgid=msgid,
                    msgstr=msgstr,
                    comment="module: construction_ui\nodoo-javascript",
                    occurrences=[
                        javascript_occurrence
                    ],
                )
            )

    for msgid in ("Task Label", "Project Overview"):
        catalogs["construction_ui"].append(
            polib.POEntry(
                msgid=msgid,
                msgstr=CUSTOM[msgid],
                comment="module: construction_ui",
                occurrences=[
                    (
                        "model_terms:ir.ui.view,arch_db:construction_ui.view_project_form_majal_360",
                        "",
                    )
                ],
            )
        )

    for module, catalog in catalogs.items():
        destination = output / module / "i18n"
        destination.mkdir(parents=True, exist_ok=True)
        catalog.save(destination / "ar_001.po")

    (output / "unmapped.txt").write_text(
        "\n---\n".join(sorted(set(unmapped))), encoding="utf-8"
    )
    print(
        f"official={official_count} custom={custom_count} mechanical={mechanical_count} "
        f"unmapped={len(set(unmapped))} total={len(source)}"
    )


if __name__ == "__main__":
    main()

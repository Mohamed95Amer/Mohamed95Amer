def official_translations():
    mapping = {}
    patterns = [
        f"{root}/*/i18n/{name}.po"
        for root in ADDON_ROOTS
        for name in ("ar", "ar_001")
    ]
    for pattern in patterns:
        for filename in glob.glob(pattern):
            try:
                for entry in polib.pofile(filename):
                    if entry.msgid and entry.msgstr and not entry.obsolete:
                        mapping.setdefault(entry.msgid, entry.msgstr)
            except (OSError, UnicodeError):
                continue
    return mapping


def entry_modules(entry):
    modules = set()
    for line in (entry.comment or "").splitlines():
        match = re.match(r"modules?:\s*(.+)", line.strip())
        if match:
            modules.update(part.strip() for part in match.group(1).split(","))
    if not modules:
        for filename, _line in entry.occurrences:
            match = re.search(r"addons/([^/]+)/", filename)
            if match:
                modules.add(match.group(1))
    return modules & set(MODULES)


def translate(source):
    official = official_translations()
    translated = 0
    custom = 0
    mechanical = 0
    for entry in source:
        if not entry.msgid or entry.msgstr:
            continue
        if entry.msgid in CUSTOM:
            entry.msgstr = CUSTOM[entry.msgid]
            custom += 1
        elif entry.msgid in official:
            entry.msgstr = official[entry.msgid]
            translated += 1
        else:
            value = entry.msgid
            for english, arabic in sorted(
                PHRASES.items(), key=lambda item: len(item[0]), reverse=True
            ):
                value = value.replace(english, arabic)
            if re.search(r"[\u0600-\u06ff]", value):
                entry.msgstr = value
                mechanical += 1
    return translated, custom, mechanical


